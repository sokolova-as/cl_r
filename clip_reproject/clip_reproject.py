    def initGui(self):
        """Create the menu entries and toolbar icons inside the QGIS GUI."""

        icon_path = ':/plugins/clip_reproject/icon.png'
        self.add_action(
            icon_path,
            text=self.tr(u'Clip Reproject'),
            callback=self.run,
            parent=self.iface.mainWindow())

        # will be set False in run()
        self.first_start = True


    def unload(self):
        """Removes the plugin menu item and icon from QGIS GUI."""
        for action in self.actions:
            self.iface.removePluginMenu(
                self.tr(u'&Clip Reproject'),
                action)
            self.iface.removeToolBarIcon(action)


    def run(self):
        """Run method that performs all the real work"""

        # Create the dialog with elements (after translation) and keep reference
        # Only create GUI ONCE in callback, so that it will only load when the plugin is started
        if self.first_start == True:
            self.first_start = False
            self.dlg = ClipReprojectDialog()

        # show the dialog
        self.dlg.show()
        # Run the dialog event loop
        result = self.dlg.exec_()
        # See if OK was pressed
        if result:
            # Получить данные из формы
            osmDir = self.dlg.osm_path.filePath()
            admShp = self.dlg.admin_shp.filePath()
            resultDir = self.dlg.result_path.filePath()
            field_name = self.dlg.field_name.text()
            attr_value = self.dlg.attr_value.text()
            zone_gsk = self.dlg.zone_gsk.text()

            # Проверка входных данных
            if not osmDir or not admShp or not resultDir or not field_name or not attr_value or not zone_gsk:
                QgsMessageLog.logMessage("Заполните все поля!", "MyPlugin", Qgis.Info)
                return

            # Открыть слой с границей и выбрать объект
            layer = QgsVectorLayer(admShp, "adm", "ogr")
            if not layer.isValid():
                QgsMessageLog.logMessage(f"Не удалось открыть слой административной границы: {admShp}", "MyPlugin", Qgis.Critical)
                return
            QgsProject.instance().addMapLayer(layer)

            # Выбор объекта по атрибуту
            try:
                layer.selectByExpression(f'"{field_name}" = \'{attr_value}\'', QgsVectorLayer.SetSelection)
                selected_features = layer.selectedFeatures()
                if not selected_features:
                    QgsMessageLog.logMessage(f"Объект с '{field_name}' = '{attr_value}' не найден в слое {admShp}", "MyPlugin", Qgis.Warning)
                    return
            except Exception as e:
                QgsMessageLog.logMessage(f"Ошибка при выборе объекта по выражению: {e}", "MyPlugin", Qgis.Critical)
                return

            # Обработать все шейп-файлы в папке
            for shpFile in glob.glob(os.path.join(osmDir, "*.shp")):
                base_name = os.path.basename(shpFile)
                clipPath = os.path.join(resultDir, base_name)
                reprojectedPath = os.path.join(resultDir, "reprojected_" + base_name) # Отдельный файл для перепроектированного слоя

                # Обрезка
                clip_params = {
                    "INPUT": shpFile,
                    "OVERLAY": QgsProcessingFeatureSourceDefinition(layer.id(), selectedFeaturesOnly=True),
                    "OUTPUT": clipPath
                }
                clip_result = processing.run("native:clip", clip_params)
                if clip_result['OUTPUT']:
                    # Перепроецирование в ГСК-2011 (зона указана в поле)
                    reproject_params = {
                        "INPUT": clipPath,
                        "TARGET_CRS": zone_gsk,
                        "OUTPUT": reprojectedPath
                    }
                    processing.run("native:reprojectlayer", reproject_params)
                    QgsMessageLog.logMessage(f"Обработан файл: {base_name}. Результат сохранен как {os.path.basename(reprojectedPath)}", "MyPlugin", Qgis.Info)
                else:
                    QgsMessageLog.logMessage(f"Ошибка при обрезке файла: {base_name}", "MyPlugin", Qgis.Warning)


            # Сообщение об успехе
            QgsMessageLog.logMessage("Все файлы обработаны!", "MyPlugin", Qgis.Success)

